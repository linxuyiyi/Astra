from __future__ import annotations

from .config import DeployConfig
from .records import atomic_write
from .runner import Runner


def render_nginx(config: DeployConfig) -> str:
    current = config.current_link
    task_api = config.ports["task_api"]
    nexus_api = config.ports["nexus_api"]
    agent = config.ports["agent_service"]
    gateway_block = ""
    if config.gateway_enabled:
        gateway_block = f"""
  # Gateway data plane: OpenAI-compatible /v1.
  location /v1/ {{
    proxy_pass http://127.0.0.1:{config.ports['gateway']};
    proxy_http_version 1.1;
    proxy_buffering off;
    proxy_request_buffering off;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
    proxy_set_header Connection "";
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
  }}
"""
    return f"""# Generated by Nexus production deployment. Do not edit by hand.
server {{
  listen {config.nginx_port};
  server_name _;
  root {current}/web/nexus/dist;
  index index.html;

  location = /agentscope-ui {{ return 308 /agentscope-ui/; }}
  location /agentscope-ui/assets/ {{
    add_header Cache-Control "public, max-age=31536000, immutable";
    try_files $uri =404;
  }}
  location /agentscope-ui/ {{
    try_files $uri $uri/ /agentscope-ui/index.html;
  }}
  location = /agentscope-api {{ return 308 /agentscope-api/; }}
  location /agentscope-api/ {{
    proxy_pass http://127.0.0.1:{agent}/;
    proxy_http_version 1.1;
    client_max_body_size 64m;
    proxy_buffering off;
    proxy_request_buffering off;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
    proxy_set_header Connection "";
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
  }}

  location /api/v1/ {{
    proxy_pass http://127.0.0.1:{nexus_api};
    proxy_http_version 1.1;
    proxy_buffering off;
    proxy_read_timeout 3600s;
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header X-Verified-UID $http_x_remote_user;
  }}

  location /api/ {{
    proxy_pass http://127.0.0.1:{task_api};
    proxy_http_version 1.1;
    proxy_buffering off;
    proxy_read_timeout 3600s;
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
  }}
{gateway_block}
  location = /docs {{
    proxy_pass http://127.0.0.1:{task_api}/docs;
    proxy_set_header Host $host;
  }}

  location = /openapi.json {{
    proxy_pass http://127.0.0.1:{task_api}/openapi.json;
    proxy_set_header Host $host;
  }}

  location ~ ^/opencode-workspace/[^/]+/index\\.html$ {{
    add_header Cache-Control "no-cache";
    try_files $uri =404;
  }}

  location /opencode-workspace/ {{
    add_header Cache-Control "public, max-age=31536000, immutable";
    try_files $uri =404;
  }}

  location / {{
    try_files $uri $uri/ /index.html;
  }}
}}
"""


def install_nginx(config: DeployConfig, runner: Runner, *, reload: bool = True) -> None:
    if not config.nginx_enabled:
        return
    atomic_write(config.nginx_conf, render_nginx(config), mode=0o644)
    check = runner.run(["nginx", "-t"])
    if check.returncode != 0:
        detail = (check.stderr or check.stdout).strip().splitlines()
        raise RuntimeError(f"nginx -t 失败：{detail[-1] if detail else check.returncode}")
    if reload:
        result = runner.run(["systemctl", "reload", "nginx"])
        if result.returncode != 0:
            result = runner.run(["nginx", "-s", "reload"])
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip().splitlines()
            raise RuntimeError(f"nginx reload 失败：{detail[-1] if detail else result.returncode}")
